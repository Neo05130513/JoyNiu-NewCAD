let temporary, Viewport
async function loadViewport() {
  if (Viewport) return Viewport
  temporary = await mkdtemp(resolve('node_modules/.cad-viewport-tests-'))
  const bundle = await rolldown({ input: resolve('src/CadModelViewport.jsx'), external: source => source === 'react' || source.startsWith('react/') || source === 'three' || source.startsWith('three/'), transform: { jsx: { runtime: 'automatic' } }, plugins: [{ name: 'ignore-viewport-css', load(id) { if (id.endsWith('.css')) return { code: '', moduleType: 'js' } } }] })
  await bundle.write({ dir: temporary, format: 'esm' }); await bundle.close()
  Viewport = (await import(pathToFileURL(resolve(temporary, 'CadModelViewport.js')).href)).default
  return Viewport
}
test.after(async () => { if (temporary) await rm(temporary, { recursive: true, force: true }) })

test('viewport exposes CAD controls and offers sketch creation only for a current selected planar face', async () => {
  const Viewport = await loadViewport()
  const surface = { ...fixture.result.faces[2], kind: 'face' }
  const markup = renderToStaticMarkup(React.createElement(Viewport, { geometry: fixture.result, selection: [surface], onPlaneSelect() {} }))
  for (const label of ['上视图', '前视图', '右视图', '等轴测', '拖动旋转模型', '拖动平移模型', '放大模型', '缩小模型', '适合窗口', '在所选平面创建草图']) assert.ok(markup.includes(label), label)
  const curved = renderToStaticMarkup(React.createElement(Viewport, { geometry: fixture.result, selection: [{ ...fixture.result.faces[6], kind: 'face' }], onPlaneSelect() {} }))
  assert.ok(!curved.includes('在所选平面创建草图'))
  const stale = renderToStaticMarkup(React.createElement(Viewport, { geometry: fixture.result, selection: [{ ...surface, selector: { ...surface.selector, geometryVersion: fixture.input.geometryVersion } }], onPlaneSelect() {} }))
  assert.ok(!stale.includes('在所选平面创建草图'))
  const fallback = renderToStaticMarkup(React.createElement(Viewport, { fallback: '/model.glb' }))
  assert.match(fallback, /此预览仅供查看/); assert.ok(!fallback.includes('在所选平面创建草图'))
})
